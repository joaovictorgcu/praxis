-- Geracao de documentos completa: a peca guarda o modelo e os campos usados
-- (para poder ser regenerada) e cada mudanca de texto vira uma versao.

-- 1. Origem da geracao e versao atual do texto.
alter table documento add column modelo_codigo varchar(40);
alter table documento add column campos_geracao text;
alter table documento add column versao_atual integer not null default 1;
alter table documento add constraint ck_documento_versao_atual check (versao_atual >= 1);

-- 2. Versoes do texto. Numero sequencial por peca; o historico so cresce
--    (restaurar uma versao cria outra). Apagar a peca apaga as versoes.
create table documento_versao (
    id           bigint generated by default as identity primary key,
    documento_id bigint       not null references documento (id) on delete cascade,
    numero       integer      not null check (numero >= 1),
    conteudo     text         not null,
    origem       varchar(20)  not null
        check (origem in ('GERACAO', 'EDICAO', 'REGENERACAO', 'RESTAURACAO')),
    autor_oab    varchar(20),
    autor_nome   varchar(150),
    criada_em    timestamp    not null,
    resumo       varchar(300),
    constraint uk_documento_versao unique (documento_id, numero)
);
create index idx_documento_versao_documento on documento_versao (documento_id);

-- 3. Pecas que ja existiam: o texto atual vira a versao 1.
insert into documento_versao (documento_id, numero, conteudo, origem, autor_oab, criada_em, resumo)
select id, 1, conteudo, 'GERACAO', gerado_por_oab, cast(gerado_em as timestamp),
       'Versão inicial (peça gerada antes do versionamento, migração V8)'
from documento;
