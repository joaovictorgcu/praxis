-- Motor de prazos completo: situacao do prazo, suspensao e retomada (CPC art. 221),
-- dilacao (CPC art. 139, VI), prazo em dobro (CPC arts. 180, 183, 186 e 229),
-- trilha de eventos por prazo e historico de execucoes da varredura.

-- 1. Situacao do prazo. "cumprido" continua existindo (e sendo gravado) para que
--    uma versao anterior da aplicacao ainda leia a tabela num rollback.
alter table prazo add column situacao varchar(20) not null default 'EM_ABERTO';
update prazo set situacao = 'CUMPRIDO' where cumprido = true;
alter table prazo add constraint ck_prazo_situacao
    check (situacao in ('EM_ABERTO', 'SUSPENSO', 'CUMPRIDO', 'CANCELADO'));
alter table prazo add constraint ck_prazo_cumprido_coerente
    check ((situacao = 'CUMPRIDO' and cumprido = true) or (situacao <> 'CUMPRIDO' and cumprido = false));

-- 2. Contagem: prerrogativa de prazo em dobro, dias acrescidos por dilacao e o
--    vencimento original (o calculado na abertura, que nunca muda).
alter table prazo add column prerrogativa varchar(30) not null default 'NENHUMA';
alter table prazo add constraint ck_prazo_prerrogativa
    check (prerrogativa in ('NENHUMA', 'MINISTERIO_PUBLICO', 'FAZENDA_PUBLICA',
                            'DEFENSORIA_PUBLICA', 'LITISCONSORTES_AUTOS_FISICOS'));
alter table prazo add column dias_acrescidos integer not null default 0;
alter table prazo add constraint ck_prazo_dias_acrescidos check (dias_acrescidos >= 0);
alter table prazo add column vencimento_original date;
update prazo set vencimento_original = vencimento;
alter table prazo alter column vencimento_original set not null;

-- A varredura e a agenda filtram por situacao e ordenam por vencimento.
create index idx_prazo_situacao on prazo (situacao, vencimento);

-- 3. Periodos de suspensao. fim e o ultimo dia parado (inclusive); nulo enquanto
--    a suspensao esta aberta. Apagar o prazo apaga os periodos.
create table prazo_suspensao (
    prazo_id bigint       not null references prazo (id) on delete cascade,
    inicio   date         not null,
    fim      date,
    motivo   varchar(300) not null,
    constraint ck_prazo_suspensao_periodo check (fim is null or fim >= inicio)
);
create index idx_prazo_suspensao_prazo on prazo_suspensao (prazo_id);

-- 4. Trilha do prazo: cada fato com o vencimento de antes e o de depois.
create table prazo_evento (
    id                  bigint generated by default as identity primary key,
    prazo_id            bigint       not null references prazo (id) on delete cascade,
    tipo                varchar(20)  not null
        check (tipo in ('ABERTURA', 'SUSPENSAO', 'RETOMADA', 'DILACAO', 'ALERTA',
                        'CUMPRIMENTO', 'CANCELAMENTO', 'REABERTURA')),
    ocorrido_em         timestamp    not null,
    vencimento_anterior date,
    vencimento_novo     date,
    detalhe             varchar(500),
    autor_oab           varchar(20),
    autor_nome          varchar(150)
);
create index idx_prazo_evento_prazo on prazo_evento (prazo_id, ocorrido_em);

-- Prazos que ja existiam ganham o evento de abertura, para a trilha nao comecar vazia.
insert into prazo_evento (prazo_id, tipo, ocorrido_em, vencimento_anterior, vencimento_novo, detalhe, autor_nome)
select id, 'ABERTURA', cast(intimacao as timestamp), null, vencimento,
       'Prazo aberto antes da trilha de eventos (migração V7).', 'migração V7'
from prazo;
insert into prazo_evento (prazo_id, tipo, ocorrido_em, vencimento_anterior, vencimento_novo, detalhe, autor_nome)
select id, 'CUMPRIMENTO', cast(cumprido_em as timestamp), vencimento, vencimento,
       'Cumprimento registrado antes da trilha de eventos (migração V7).', 'migração V7'
from prazo
where cumprido = true and cumprido_em is not null;

-- 5. Historico da varredura: cada execucao, automatica ou manual, com o resultado.
create table varredura_execucao (
    id               bigint generated by default as identity primary key,
    origem           varchar(20)  not null check (origem in ('AUTOMATICA', 'MANUAL')),
    data_referencia  date         not null,
    iniciada_em      timestamp    not null,
    concluida_em     timestamp    not null,
    prazos_avaliados integer      not null check (prazos_avaliados >= 0),
    alertas_emitidos integer      not null check (alertas_emitidos >= 0),
    solicitante      varchar(150),
    constraint ck_varredura_duracao check (concluida_em >= iniciada_em)
);
create index idx_varredura_iniciada on varredura_execucao (iniciada_em);
