create table acesso_ao_processo (
    id               bigint generated by default as identity primary key,
    numero_processo  varchar(25)   not null,
    oab              varchar(20)   not null,
    concedido_por    varchar(20)   not null,
    concedido_em     date          not null,
    expira_em        date,
    revogado_em      date,
    motivo_revogacao varchar(500)
);
create index idx_acesso_processo on acesso_ao_processo (numero_processo);

create table solicitacao_acesso (
    id               bigint generated by default as identity primary key,
    numero_processo  varchar(25)   not null,
    oab_solicitante  varchar(20)   not null,
    justificativa    varchar(1000) not null,
    solicitado_em    date          not null,
    status           varchar(20)   not null,
    decidido_em      date,
    decidido_por_oab varchar(20),
    motivo_negacao   varchar(500)
);
create index idx_solicitacao_processo on solicitacao_acesso (numero_processo);

create table auditoria_acesso (
    id              bigint generated by default as identity primary key,
    tipo_evento     varchar(30)  not null,
    conteudo_tipo   varchar(20),
    conteudo_id     bigint,
    numero_processo varchar(25)  not null,
    oab             varchar(20),
    usuario_id      bigint,
    usuario_nome    varchar(150),
    quando          timestamp    not null,
    resultado       varchar(10)  not null,
    motivo          varchar(500)
);
create index idx_auditoria_processo on auditoria_acesso (numero_processo);
create index idx_auditoria_oab on auditoria_acesso (oab);
